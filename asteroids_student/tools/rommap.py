#!/usr/bin/env python3
"""rommap.py - write docs/ROM_MAP.md: which ROM addresses hold what.

    python3 tools/rommap.py games/asteroids.json games/swarm.json \
        games/duel.json games/sudden.json -o docs/ROM_MAP.md

The addresses are computed by the same linker that writes games.mem and
games.coe, so the map always matches the image built from the same files.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import geformat as gf     # noqa: E402
import gamec              # noqa: E402

OWNER = {0: "-", 1: "P1", 2: "P2"}


def field_table(fields, nwords):
    out = ["| word | bits | field | meaning |", "|---|---|---|---|"]
    for w in range(nwords):
        for f in sorted([f for f in fields if f.word == w], key=lambda f: -f.lsb):
            bits = "[%d]" % f.lsb if f.width == 1 else "[%d:%d]" % (f.lsb + f.width - 1, f.lsb)
            out.append("| W%d | %s | `%s`%s | %s |" % (w, bits, f.name, " (signed)" if f.signed else "", f.doc))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("games", nargs="+")
    ap.add_argument("-o", "--out", default="docs/ROM_MAP.md")
    a = ap.parse_args(argv)
    img = gamec.link([gamec.parse_game(p) for p in a.games])

    L = []
    L += ["# ROM map: what lives at which address of games.mem / games.coe",
          "",
          "Generated by `tools/rommap.py` from the same linker that writes the",
          "image, so every address here matches `build/games.mem` and",
          "`build/games.coe` built from the same JSON files. Do not edit by hand.",
          "`build/games.lst` has every word decoded field by field.",
          "",
          "## 1. The whole image",
          "",
          "The ROM is %d words x 32 bits. `.mem` line N (counting from 0, after the"
          % img.depth,
          "comment lines) and `.coe` vector entry N are both ROM address N.",
          "%d words are used; the rest are 0." % img.used,
          "",
          "| Address range | Words | Contents |",
          "|---|---|---|",
          "| 0x000-0x%03X | %d | game directory: word g points to game g's header |"
          % (gf.DIR_WORDS - 1, gf.DIR_WORDS)]
    names = {"hdr": "header (sizes, base addresses, arena, scoring, lives, waves)",
             "pal": "palette, 16 colours (12-bit RGB in bits 11:0)",
             "obj": "object records, 3 words each",
             "inp": "input mappings, 1 word each",
             "rule": "rules, 2 words each"}
    for g in img.games:
        if g is None:
            continue
        A = g.addr
        for key, nxt in (("hdr", "pal"), ("pal", "obj"), ("obj", "inp"), ("inp", "rule"), ("rule", "end")):
            n = A[nxt] - A[key]
            if n:
                L.append("| 0x%03X-0x%03X | %d | game %d (%s): %s |"
                         % (A[key], A[nxt] - 1, n, g.slot, g.title, names[key]))
    L.append("| 0x%03X-0x%03X | %d | unused, 0 |" % (img.used, img.depth - 1, img.depth - img.used))
    L += ["",
          "## 2. How the hardware walks it",
          "",
          "1. A button selects game g (0..3). The loader reads **directory word g**:",
          "   bits 10:0 = header address, bits 23:16 = format version (2), bit 31 = valid.",
          "2. It reads the **%d header words**. H0 holds the counts (objects, inputs," % gf.HDR_WORDS,
          "   rules) and the magic byte 0xA5; H1/H2 hold the base addresses of the",
          "   objects, inputs, rules and palette; H3..H9 hold the arena and game settings.",
          "3. It copies the **16 palette words** into the colour table.",
          "4. It copies **object record i** (ROM words `obj_base + 3i`, `+1`, `+2`) into",
          "   **object RAM address i** as one 96-bit word `{W2, W1, W0}`; RAM slots",
          "   from n_obj to 63 are cleared.",
          "5. While the game runs, the engine reads the **input mappings** and **rules**",
          "   straight from the ROM every frame (they are never copied), and re-reads an",
          "   object's ROM record when it respawns, is spawned from a pool, becomes a",
          "   SPLIT fragment, or is reloaded by a new wave.",
          ""]

    for g in img.games:
        if g is None:
            continue
        A = g.addr
        L += ["## Game %d: %s (`%s`)" % (g.slot, g.title, os.path.basename(g.source)), ""]
        L += ["Directory word **0x%03X** = `%08X` -> header at 0x%03X."
              % (g.slot, img.words[g.slot], A["hdr"]), ""]
        L += ["**Header** 0x%03X-0x%03X:" % (A["hdr"], A["pal"] - 1), "",
              "| Addr | Word | Fields |", "|---|---|---|"]
        for k in range(gf.HDR_WORDS):
            ad = A["hdr"] + k
            L.append("| 0x%03X | `%08X` | %s |" % (ad, img.words[ad], img.notes[ad].split("  ", 1)[1]))
        L += ["", "**Palette** 0x%03X-0x%03X: " % (A["pal"], A["obj"] - 1) + ", ".join(
            "%d `%s` #%03X @0x%03X" % (i, nm, rgb, A["pal"] + i)
            for i, (nm, rgb) in enumerate(g.palette)) + "; the rest are 0.", ""]
        L += ["**Objects** 0x%03X-0x%03X (RAM slot = index; pool objects start disabled and"
              " are activated by SPAWN or SPLIT):" % (A["obj"], A["inp"] - 1), "",
              "| RAM slot | ROM W0 / W1 / W2 | Name | Class | Owner | Start (x, y) | Size | Velocity | Notes |",
              "|---|---|---|---|---|---|---|---|---|"]
        for i, o in enumerate(g.objects):
            b = A["obj"] + gf.OBJ_WORDS * i
            notes = []
            if o.get("_pool"):
                notes.append("pool")
            if not o["enabled"]:
                notes.append("starts disabled")
            if o["mark"]:
                notes.append("facing marker")
            if o["tmode"] == gf.TMODE["SHIELD"] and o["timer"]:
                notes.append("shield %d frames" % o["timer"])
            if o["tmode"] == gf.TMODE["LIFETIME"]:
                notes.append("lives %d frames" % o["timer"])
            L.append("| %d | 0x%03X / 0x%03X / 0x%03X | %s | %s | %s | (%d, %d) | %d x %d | (%d, %d) | %s |"
                     % (i, b, b + 1, b + 2, o["_name"], g.class_name(o["class"]), OWNER[o["owner"]],
                        o["x"], o["y"], o["w"], o["h"], o["vx"], o["vy"], ", ".join(notes)))
        L += ["", "**Input mappings** 0x%03X-0x%03X:" % (A["inp"], A["rule"] - 1), "",
              "| Addr | Word | Meaning |", "|---|---|---|"]
        for i, m in enumerate(g.inputs):
            ad = A["inp"] + i
            L.append("| 0x%03X | `%08X` | %s |" % (ad, img.words[ad], gamec.describe_input(g, m)))
        L += ["", "**Rules** 0x%03X-0x%03X (checked in this order):" % (A["rule"], A["end"] - 1), "",
              "| Addr | Words | When | Then |", "|---|---|---|---|"]
        for i, r in enumerate(g.rules):
            ad = A["rule"] + 2 * i
            w, t = gamec.describe_rule(g, r)
            L.append("| 0x%03X-0x%03X | `%08X` `%08X` | %s | %s |"
                     % (ad, ad + 1, img.words[ad], img.words[ad + 1], w, t))
        L.append("")

    L += ["## Bit layouts", "",
          "### Directory word", ""] + field_table(gf.DIR_FIELDS, 1) + [
          "", "### Object record (3 words; in object RAM: bits 31:0 = W0, 63:32 = W1, 95:64 = W2)", ""] + \
        field_table(gf.OBJ_FIELDS, gf.OBJ_WORDS) + ["", "### Input mapping (1 word)", ""] + \
        field_table(gf.INP_FIELDS, 1) + ["", "### Rule (2 words)", ""] + \
        field_table(gf.RULE_FIELDS, gf.RULE_WORDS) + [
          "", "Header fields and the MOVE / SPAWN parameter layouts are in",
          "[MEMORY_FORMAT.md](MEMORY_FORMAT.md).", ""]

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write("\n".join(L))
    print("wrote %s" % a.out)


if __name__ == "__main__":
    main()
